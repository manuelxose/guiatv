import test from 'node:test';
import assert from 'node:assert/strict';
import { createClient } from 'redis';
import { ValkeyAnalyticsRepository } from './ValkeyAnalyticsRepository';

test('Valkey realtime pages tracks coverage, users and exclusions without a capped event log', { skip: !process.env.TEST_REDIS_URL }, async () => {
  const redisUrl = process.env.TEST_REDIS_URL!;
  const repo = new ValkeyAnalyticsRepository(redisUrl);
  const admin = createClient({ url: redisUrl });
  const previous = process.env.ANALYTICS_EXCLUDED_IPS;
  process.env.ANALYTICS_EXCLUDED_IPS = '203.0.113.9';
  const now = new Date();
  const at = (seconds: number) => new Date(now.getTime() - seconds * 1000);
  try {
    await repo.connect();
    await admin.connect();
    const start = async (sessionId: string, ip = '198.51.100.1') => repo.startSession({ sessionId, anonId: sessionId, startedAt: now, lastSeenAt: now, ip });
    await start('one');
    await start('two');
    await start('admin');
    await start('excluded', '::ffff:cb00:7109');
    await repo.startSession({ sessionId: 'duration', anonId: 'duration', startedAt: at(120), lastSeenAt: at(30), ip: '198.51.100.1' });
    await repo.startSession({ sessionId: 'geo', anonId: 'geo', startedAt: now, lastSeenAt: now, ip: '198.51.100.1', country: 'ES', region: 'MD', city: 'Madrid', latitude: 40.4, longitude: -3.7 });
    const live = await repo.getLiveSessions(90, 50);
    assert.equal(live.find((session) => session.sessionId === 'duration')?.durationSec, 90);
    const geo = live.find((session) => session.sessionId === 'geo');
    assert.deepEqual([geo?.country, geo?.region, geo?.city, geo?.latitude, geo?.longitude], ['ES', 'MD', 'Madrid', 40.4, -3.7]);
    const before = await repo.countLiveSessions(90);
    await repo.startSession({ sessionId: 'idle', anonId: 'idle', startedAt: now, lastSeenAt: now, metadata: { activity: { idleSec: 300 } } });
    assert.equal(await repo.countLiveSessions(90), before);
    await repo.heartbeatSession({ sessionId: 'idle', lastSeenAt: now, metadata: { activity: { idleSec: 0 } } });
    assert.equal(await repo.countLiveSessions(90), before + 1);
    await repo.heartbeatSession({ sessionId: 'idle', lastSeenAt: now, metadata: { activity: { idleSec: 300 } } });
    await repo.heartbeatSession({ sessionId: 'idle', lastSeenAt: now });
    assert.equal(await repo.countLiveSessions(90), before);
    assert.equal((await repo.getLiveSessions(90, 50)).some((s) => s.sessionId === 'idle'), false);
    assert.ok(await admin.exists('analytics:session:idle'));
    (repo as any).piiMode = 'none';
    const previouslyLocated = (await repo.getLiveSessions(90, 50)).find((session) => session.sessionId === 'geo');
    assert.equal(previouslyLocated?.city, undefined);
    await repo.startSession({ sessionId: 'geo-private', anonId: 'geo-private', startedAt: now, lastSeenAt: now, ip: '198.51.100.1', country: 'ES', city: 'Madrid', latitude: 40.4, longitude: -3.7 });
    const privateSession = (await repo.getLiveSessions(90, 50)).find((session) => session.sessionId === 'geo-private');
    assert.equal(privateSession?.country, undefined);
    assert.equal(privateSession?.latitude, undefined);
    (repo as any).piiMode = 'anonymized';
    const event = (eventId: string, sessionId: string, type: string, path: string, seconds: number, ip = '198.51.100.1') => repo.createEvent({ eventId, sessionId, anonId: sessionId, type, path, occurredAt: at(seconds), ip });
    await event('1', 'one', 'page_view', '/a', 10);
    await event('2', 'one', 'click', '/a', 20);
    await event('3', 'two', 'page_view', '/a', 80);
    await event('4', 'one', 'page_view', '/b', 80);
    await event('5', 'admin', 'page_view', '/a', 10);
    await event('6', 'excluded', 'page_view', '/a', 10);
    await repo.markExcludedSession('admin');
    assert.equal((await repo.getRealtimePages(now))?.partial, true);
    await admin.set('analytics:realtime:coverage:v2', String(now.getTime() - 31 * 60_000));
    const report = (await repo.getRealtimePages(now))!;
    assert.equal(report.partial, false);
    assert.equal(report.activeUsers, 2);
    assert.equal(report.pageViews, 3);
    assert.equal(report.minutes[29].users, 1);
    assert.equal(report.minutes[28].users, 2);
    assert.deepEqual(report.pages, [{ path: '/a', users: 2, views: 2 }, { path: '/b', users: 1, views: 1 }]);
    process.env.ANALYTICS_EXCLUDED_IPS = '203.0.113.9,198.51.100.7';
    const changedPolicy = (await repo.getRealtimePages(now))!;
    assert.equal(changedPolicy.partial, true);
    assert.equal(changedPolicy.activeUsers, 0);
    process.env.ANALYTICS_EXCLUDED_IPS = '203.0.113.9';
    (repo as any).eventLogMax = 2;
    const cappedLog = (await repo.getRealtimePages(now))!;
    assert.equal(cappedLog.partial, true);
    assert.equal(cappedLog.pageViews, 3);
    (repo as any).eventLogMax = 5000;
    await admin.lPush('analytics:events', JSON.stringify({ eventId: 'legacy-only', occurredAt: at(10).toISOString() }));
    assert.equal((await repo.getRealtimePages(now))?.partial, true);
    await admin.lPop('analytics:events');
    await event('7', 'unknown-session', 'page_view', '/a', 10);
    const partial = (await repo.getRealtimePages(now))!;
    assert.equal(partial.partial, true);
    assert.equal(partial.activeUsers, 2);
  } finally {
    if (previous === undefined) delete process.env.ANALYTICS_EXCLUDED_IPS;
    else process.env.ANALYTICS_EXCLUDED_IPS = previous;
    await admin.quit();
    await (repo as any).client.quit();
  }
});
