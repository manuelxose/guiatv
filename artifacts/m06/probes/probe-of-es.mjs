import fs from 'node:fs';
const r = await fetch('https://raw.githubusercontent.com/openfootball/football.json/master/2026-27/es.1.json', { headers: { 'User-Agent': 'guiatv-m06-probe/1.0' } });
const j = await r.json();
const ms = j.matches || [];
console.log('name', j.name, 'matches', ms.length);
const withScore = ms.filter(m => m.score && (m.score.ft || m.score.ht));
console.log('withScore', withScore.length);
console.log('first', JSON.stringify(ms[0]));
console.log('lastScored', JSON.stringify(withScore[withScore.length - 1]));
const keys = [...new Set(ms.flatMap(m => Object.keys(m)))];
console.log('matchKeys', JSON.stringify(keys));
const scoreKeys = [...new Set(withScore.flatMap(m => Object.keys(m.score)))];
console.log('scoreKeys', JSON.stringify(scoreKeys));
const withGoalsList = ms.filter(m => m.goals && m.goals.length);
console.log('withGoalsList', withGoalsList.length, withGoalsList[0] ? JSON.stringify(withGoalsList[0].goals.slice(0,3)) : 'none');
const rounds = [...new Set(ms.map(m => m.round))];
console.log('rounds', rounds.length, JSON.stringify(rounds.slice(0, 5)));
const teams = [...new Set(ms.flatMap(m => [m.team1, m.team2]))];
console.log('teams', teams.length);
fs.writeFileSync('artifacts/m06/probes/openfootball-es-sample.json', JSON.stringify({ name: j.name, sample: ms[0], lastScored: withScore[withScore.length-1] }, null, 2));
